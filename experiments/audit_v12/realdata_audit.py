# ---------------------------------------------------------------- M3: rungs and default side by side
L += ["## M3. Protocol rungs and the post hoc default, side by side", "",
      "The protocol's primary SIGNET analysis was rung 1 and its secondary analysis rung 2 (PROTOCOL_realdata_v1.md, section 5).",
      "The default (one failed group or one broken cell, at the highest rung) was computed after the protocol.",
      "It is unbounded by construction whenever one cell measures the effect, because the analysis that omits that cell",
      "has nothing left to bound the effect, whatever the data.", "",
      "| Question | Cells measuring the effect | Capacity for benefit, rung 1 / 2 / 3 | Rung 1 | Structural rung (2) | p benefit, rung 2 | Rung 3 | p benefit, rung 3 | Group-tolerant, highest rung | Default, highest rung |", "|---|---|---|---|---|---|---|---|---|---|"]
m3 = {}
for key, lab, (M, R), cf in (("hormone_therapy_cvd", "Hormone therapy and cardiovascular disease", model_A(), [1, 0]),
                             ("sigmoidoscopy", "Sigmoidoscopy and distal cancer death", model_B(), [1]),
                             ("vitamin_E", "Vitamin E and coronary disease", model_C(), [1])):
    rec = dict(n_effect_cells=int(sum(1 for x in M.rows if abs(np.dot(x["K"], cf)) > 0)))
    for rn in ("R1", "R2", "R3"):
        if rn not in R:
            rec[rn] = None; continue
        s = sset(M, R[rn], cf)
        s["capacity_benefit"] = bool(capacity(M, R[rn], cf)["above"])
        s["p_benefit"], s["p_benefit_upper"] = pval(M, R[rn], cf, "benefit", s["empty"])
        s["p_harm"], _ = pval(M, R[rn], cf, "harm", s["empty"])
        mt = model_test(M, R[rn], 0.05); s["model_test_p"] = mt.get("p")
        rec[rn] = s
    top = [rn for rn in ("R3", "R2", "R1") if rn in R][0]
    rec["top"] = top
    rec["k1"] = tset(M, R[top], cf, droppable=R[top])
    rec["default"] = dset(M, R[top], cf)
    m3[key] = rec
    g = lambda rn, k: "not available" if rec[rn] is None else rec[rn][k]
    pb = lambda rn: "not available" if rec[rn] is None else (f"{rec[rn]['p_benefit']:.4f}" if rec[rn]["p_benefit"] is not None else "not reported")
    capt = " / ".join("n/a" if rec[rn] is None else ("yes" if rec[rn]["capacity_benefit"] else "no") for rn in ("R1", "R2", "R3"))
    L.append(f"| {lab} | {rec['n_effect_cells']} | {capt} | {g('R1', 'text')} | {g('R2', 'text')} | {pb('R2')} | {g('R3', 'text')} | {pb('R3')} | {rec['k1']['text']} | {rec['default']['text']} |")
out["rungs_and_default"] = m3
L.append("")

# ---------------------------------------------------------------- D4: certificate and test limits by rung (sigmoidoscopy)
L += ["## D4, N11. Certificate limit and test-based limit at each rung (sigmoidoscopy)", "",
      "The reported limit is the tighter of the certificate limit (level 0.0125 per side) and the test-based limit (level 0.025).", "",
      "| Rung | Side | Certificate weights (distal, proximal) | SD of the certified combination | Certificate limit (RR) | Test-based limit (RR) | Reported limit (RR) | Certificate unique |", "|---|---|---|---|---|---|---|---|"]
M, R = model_B(); d4 = {}
for rn in ("R1", "R2"):
    cb = cert_bounds(M, R[rn], [1], 0.0125)
    cs = conf_set(M, R[rn], [1], 0.025)
    s = signet_set(M, R[rn], [1], 0.05)
    for side in ("lo", "hi"):
        ct = cb["cert_" + side]
        cr = certificate_range(M, R[rn], [1], side)
        w = None if ct is None else [float(ct["weights"].get("B_distal", 0.0)), float(ct["weights"].get("B_proximal", 0.0))]
        d4[f"{rn}_{side}"] = dict(weights=w, sd=None if ct is None else ct["sd"], cert=float(cb[side]), test=float(cs[side]),
                                  reported=float(s[side]), unique=None if cr is None else cr["unique"])
        fr = lambda v: "unbounded" if not np.isfinite(v) else f"{np.exp(v):.3f}"
        L.append(f"| {rn[1]} | {'lower' if side == 'lo' else 'upper'} | {'none' if w is None else f'{w[0]:.3f}, {w[1]:.3f}'} | "
                 f"{'n/a' if ct is None else format(ct['sd'], '.4f')} | {fr(cb[side])} | {fr(cs[side])} | {fr(s[side])} | {'n/a' if cr is None else ('yes' if cr['unique'] else 'no')} |")
