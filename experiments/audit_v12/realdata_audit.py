Z = float(sst.norm.ppf(0.975))
D = RD.load()


def rr(lo, hi, nd=3):
    f = lambda v: ("0" if v < 0 else "unbounded") if (v is None or not np.isfinite(v)) else f"{np.exp(v):.{nd}f}"
    return f"{f(lo)} to {f(hi)}"


def est(m, lo, hi, nd=2):
    return f"{np.exp(m):.{nd}f} ({np.exp(lo):.{nd}f} to {np.exp(hi):.{nd}f})"


def sset(M, inc, cf, **kw):
    s = signet_set(M, inc, cf, 0.05, **kw)
    if s["empty"]:
        return dict(empty=True, lo=None, hi=None, text="empty", reason=s.get("reason"))
    return dict(empty=False, lo=float(s["lo"]), hi=float(s["hi"]), text=rr(s["lo"], s["hi"]),
                cert_lo=float(s["cert"]["lo"]), cert_hi=float(s["cert"]["hi"]),
                test_lo=float(s["cc"]["lo"]), test_hi=float(s["cc"]["hi"]))


def pval(M, inc, cf, claim, empty):
    c = claim_pvalue(M, inc, cf, claim, alpha=0.05, empty=empty)
    return c["p"], c["p_upper"]


def tset(M, inc, cf, **kw):
    t = tolerant_set(M, inc, cf, k=1, alpha=0.05, **kw)
    return dict(empty=t["empty"], lo=t["lo"], hi=t["hi"], text="empty" if t["empty"] else rr(t["lo"], t["hi"]))


def dset(M, inc, cf):
    d = default_set(M, inc, cf, alpha=0.05)
    return dict(empty=d["empty"], lo=d["lo"], hi=d["hi"], text="empty" if d["empty"] else rr(d["lo"], d["hi"]))


def clean(o):
    if isinstance(o, dict):
        return {str(k): clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [clean(v) for v in o]
    if isinstance(o, (bool, np.bool_)):
        return bool(o)
    if isinstance(o, (float, np.floating)):
        return float(o) if np.isfinite(o) else ("inf" if o > 0 else "-inf")
    if isinstance(o, (int, np.integer)):
        return int(o)
    return o


