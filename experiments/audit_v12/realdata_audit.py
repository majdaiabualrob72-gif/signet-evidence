# ---------------------------------------------------------------- D6: inflated variances (hormone therapy)
L += ["## D6. Hormone therapy with inflated variances", "",
      "The source gives best estimates and states that heterogeneity among the studies prevented pooling, so the published",
      "intervals understate the uncertainty of a summary. Standard errors of both cells were multiplied by a common factor.", "",
      "| SE factor | Conventional, cardiovascular (RR, 95% CI), p | BA-S | Calibration against total cancer, p | SIGNET rung 1 | Rung 2 | Rung 3 (exact null control) | p benefit, rung 3 | Group-tolerant, rung 3 | Default |", "|---|---|---|---|---|---|---|---|---|---|"]
d6 = {}
for f in (1.0, 1.5, 2.0, 3.0):
    M, R = model_A(f, f)
    a, c = D["A_cvd"], D["A_cancer"]
    m, se = a["y"], a["se"] * f
    bs = RD.bayes_bias([m], [se], -0.15, 0.15)
    mc, sc_ = a["y"] - c["y"], float(np.sqrt((a["se"] * f) ** 2 + (c["se"] * f) ** 2))
    rec = dict(conventional=dict(lo=m - Z * se, hi=m + Z * se, p=float(2 * sst.norm.sf(abs(m / se)))),
               ba_s=dict(m=bs[0], lo=bs[0] - Z * bs[1], hi=bs[0] + Z * bs[1]),
               nco=dict(m=mc, lo=mc - Z * sc_, hi=mc + Z * sc_, p=float(2 * sst.norm.sf(abs(mc / sc_)))))
    for rn in ("R1", "R2", "R3"):
        s = sset(M, R[rn], [1, 0])
        s["p_benefit"], s["p_benefit_upper"] = pval(M, R[rn], [1, 0], "benefit", s["empty"])
        rec[rn] = s
    rec["k1"] = tset(M, R["R3"], [1, 0], droppable=R["R3"])
    rec["default"] = dset(M, R["R3"], [1, 0])
    d6[str(f)] = rec
    L.append(f"| {f:g} | {est(m, m - Z * se, m + Z * se)}, p = {rec['conventional']['p']:.2g} | {est(bs[0], bs[0] - Z * bs[1], bs[0] + Z * bs[1])} | "
             f"{est(mc, mc - Z * sc_, mc + Z * sc_)}, p = {rec['nco']['p']:.2g} | {rec['R1']['text']} | {rec['R2']['text']} | {rec['R3']['text']} | "
             f"{rec['R3']['p_benefit']:.4f} | {rec['k1']['text']} | {rec['default']['text']} |")
out["hormone_therapy_inflated_variance"] = d6
L.append("")

# ---------------------------------------------------------------- D7: trial validity as a named group
L += ["## D7. Beta-carotene (method-agreement case) with trial validity as a named rung-3 group", "",
      "Frozen encoding (amendment 2): the trial cell carries no bias process, so trial validity is assumed at every rung and",
      "cannot be dropped by group tolerance. Post hoc encoding: the trial cell carries a validity process A, and A = 0 is a named",
      "rung-3 group (trial_valid).", "",
      "| Encoding | Rung | Assumptions in force | SIGNET set (RR) | Model test p | Group-tolerant set | Default |", "|---|---|---|---|---|---|---|"]
d7 = {}
for lab, named in (("frozen (trial validity built in)", False), ("post hoc (trial validity named)", True)):
    M, R = model_D(named)
    top = "R3" if named else "R2"
    for rn, inc in R.items():
        s = sset(M, inc, [1])
        mt = model_test(M, inc, 0.05)
        k1 = tset(M, inc, [1], droppable=inc) if rn != "R1" else None
        dd = dset(M, inc, [1]) if rn == top else None
        d7[f"{'named' if named else 'frozen'}_{rn}"] = dict(set=s, model_test_p=mt.get("p"), k1=k1, default=dd, include=inc)
        L.append(f"| {lab} | {rn[1]} | {', '.join(inc)} | {s['text']} | {mt.get('p'):.4f} | {'not computed' if k1 is None else k1['text']} | {'' if dd is None else dd['text']} |")
out["beta_carotene_trial_validity"] = d7
L += ["", "Published triangulation (Shapland et al.): 1.01 (0.99 to 1.02).", ""]

