# ---------------------------------------------------------------- N4 / M1: conventional comparator
L += ["## M1, N4. The conventional comparator", "",
      "Single published estimates were not pooled by this analysis. The analysis reconstructs a standard error",
      "from the published limits, SE = (ln U - ln L) / (2 x 1.96), and a symmetric interval around the point estimate.", "",
      "| Input | Published estimate (95% CI) | Reconstructed symmetric interval | SE (log) | z | Two-sided p |", "|---|---|---|---|---|---|"]
conv = {}
for cid, lab in (("A_cvd", "Hormone therapy, cardiovascular disease (single published best estimate)"),
                 ("A_cancer", "Hormone therapy, total cancer (single published best estimate)"),
                 ("B_distal", "Sigmoidoscopy, distal cancer death (single study)"),
                 ("B_proximal", "Sigmoidoscopy, proximal cancer death (single study; control)"),
                 ("C_nhs", "Vitamin E, Nurses' Health Study (single cohort)"),
                 ("C_hpfs", "Vitamin E, Health Professionals Follow-up Study (single cohort)")):
    r = D[cid]; m, se = r["y"], r["se"]
    p = float(2 * sst.norm.sf(abs(m / se)))
    conv[cid] = dict(point=r["point"], lower=r["lower"], upper=r["upper"], se=se, z=m / se, p=p,
                     recon_lower=float(np.exp(m - Z * se)), recon_upper=float(np.exp(m + Z * se)))
    L.append(f"| {lab} | {r['point']:.2f} ({r['lower']:.2f} to {r['upper']:.2f}) | {np.exp(m - Z * se):.3f} to {np.exp(m + Z * se):.3f} | {se:.4f} | {m / se:.3f} | {p:.2e} ({p:.4f}) |")
out["conventional_inputs"] = conv
L += ["", "Random-effects pooling was performed only where two estimates measured the same effect.", "",
      "| Pooled inputs | k | tau2 | q | Estimate | Wald (normal) | Hartung-Knapp (t, factor q) | Modified Hartung-Knapp (t, factor max(1, q)) |", "|---|---|---|---|---|---|---|---|"]
rev = {}
for key, lab, ids in (("vitamin_E", "Vitamin E: two cohorts", ("C_nhs", "C_hpfs")),
                      ("beta_carotene_nonrandomized", "Beta-carotene: Mendelian randomization and multivariable regression", ("D_mr", "D_mvr"))):
    v = re_variants([D[i]["y"] for i in ids], [D[i]["se"] for i in ids])
    rev[key] = {k: (list(x) if isinstance(x, tuple) else x) for k, x in v.items()}
    f = lambda t: f"{np.exp(t[0]):.2f} to {np.exp(t[1]):.2f}, p = {t[2]:.2g}"
    L.append(f"| {lab} | {v['k']} | {v['tau2']:.4f} | {v['q']:.3f} | {np.exp(v['est']):.2f} | {f(v['wald'])} | {f(v['hk'])} | {f(v['mhk'])} |")
out["re_variants"] = rev
L += ["", "With two estimates the t quantile has one degree of freedom (12.71). The archived real-data script used the Wald",
      "interval; the simulation comparator used the modified Hartung-Knapp interval.", ""]

# ---------------------------------------------------------------- D2: BA-S independent vs shared
L += ["## D2. BA-S with independent or shared bias terms", "",
      "Prior per signed process N(-0.15, 0.15^2). Independent: one bias term per cell. Shared: one healthy-user term",
      "common to the cells that carry it. With one cell the two specifications coincide.", "",
      "| Question | Cells measuring the effect | BA-S independent | BA-S shared |", "|---|---|---|---|"]
bas = {}


def ba_ind(ys, ses, m_b=-0.15, s_b=0.15):
    return RD.bayes_bias(ys, ses, m_b, s_b)


def ba_shared(ys, ses, m_b=-0.15, s_b=0.15):
    ys, ses = np.asarray(ys, float), np.asarray(ses, float)
    n = len(ys)
    S = np.diag(ses ** 2) + s_b ** 2 * np.ones((n, n))
    Si = np.linalg.inv(S); one = np.ones(n)
    var = 1 / float(one @ Si @ one)
    return var * float(one @ Si @ (ys - m_b)), float(np.sqrt(var))


for key, lab, ids in (("hormone_therapy_cvd", "Hormone therapy and cardiovascular disease", ("A_cvd",)),
                      ("sigmoidoscopy", "Sigmoidoscopy and distal cancer death", ("B_distal",)),
                      ("vitamin_E", "Vitamin E and coronary disease", ("C_nhs", "C_hpfs"))):
    ys, ses = [D[i]["y"] for i in ids], [D[i]["se"] for i in ids]
    a, b = ba_ind(ys, ses), ba_shared(ys, ses)
    bas[key] = dict(independent=dict(m=a[0], se=a[1], lo=a[0] - Z * a[1], hi=a[0] + Z * a[1]),
                    shared=dict(m=b[0], se=b[1], lo=b[0] - Z * b[1], hi=b[0] + Z * b[1]))
    L.append(f"| {lab} | {len(ids)} | {est(a[0], a[0] - Z * a[1], a[0] + Z * a[1])} | {est(b[0], b[0] - Z * b[1], b[0] + Z * b[1])} |")
out["ba_s"] = bas
L.append("")

