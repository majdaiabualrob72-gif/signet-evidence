"""Build the simulation tables reported in the manuscript and Supplementary S4 and S5.

Reads the JSON outputs of benchmark.py and benchmark_v2.py (no re-simulation) and writes
tables_simulation.md. Every number in the manuscript's simulation results comes from this file.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)

KEY = [("RE (all designs)", "RE"), ("FE (all designs)", "FE"), ("RE (trials only)", "RE trials"),
       ("BA-U (unsigned bias priors)", "BA-U"), ("BA-S (elicited directions and magnitudes)", "BA-S"),
       ("NCO-cal (calibrated, RE)", "NCO-cal"), ("DECODE", "DECODE"),
       ("SIGNET R1", "SIGNET R1"), ("SIGNET R2", "SIGNET R2"), ("SIGNET R3", "SIGNET R3"),
       ("SIGNET protocol", "SIGNET protocol"), ("SIGNET R3 k=1", "SIGNET R3 k=1")]


def f(x, d=3):
    if x is None:
        return "NA"
    return f"{x:.{d}f}"


def load(fn):
    try:
        return json.load(open(fn))["results"]
    except FileNotFoundError:
        return {}


def main():
    base = json.load(open("all_scenarios_summary.json"))
    het = load("benchmark_v2_hetallow.json")
    bnd = load("benchmark_v2_bounded.json")
    cr = load("benchmark_v2_cellrobust.json")
    sw = load("benchmark_v2_sweep.json")
    out = []
    out.append("# Simulation tables (generated by make_tables.py from archived JSON outputs)\n")
    out.append("Coverage of the true effect / median width of bounded sets (log scale) / share unbounded / "
               "rate of certified benefit / rate of certified harm. 400 literatures per scenario unless stated.\n")
    for sc, v in base.items():
        out.append(f"\n## {sc}\n")
        out.append("| Method | Coverage | MC SE | Median width | Unbounded | Benefit | Harm |")
        out.append("|---|---|---|---|---|---|---|")
        for k, lab in KEY:
            x = v.get(k)
            if not isinstance(x, dict):
                continue
            cov = x["coverage"]
            n = x.get("n", 400) or 400
            se = None if cov is None else (cov * (1 - cov) / n) ** 0.5
            out.append(f"| {lab} | {f(cov)} | {f(se)} | {f(x['median_width'], 2)} | {f(x.get('unbounded', 0), 2)} | "
                       f"{f(x['benefit'], 2)} | {f(x['harm'], 2)} |")
        extra = [(r, d) for r, d in ((het, "heterogeneity allowance"), (bnd, "magnitude rung"), (cr, "group or cell tolerance"))
                 if sc in r]
        for r, d in extra:
            for k, x in r[sc].items():
                if isinstance(x, dict) and "coverage" in x:
                    cov = x["coverage"]
                    se = None if cov is None else (cov * (1 - cov) / x["n"]) ** 0.5
                    out.append(f"| {k} (n = {x['n']}) | {f(cov)} | {f(se)} | {f(x['median_width'], 2)} | "
                               f"{f(x.get('unbounded', 0), 2)} | {f(x['benefit'], 2)} | {f(x['harm'], 2)} |")
        for lab in ("R3 rejection rate", "R3 rejection when a validity zero failed", "R3 rejection when none failed"):
            if lab in v:
                out.append(f"\n{lab}: {f(v[lab])}")
    if sw:
        out.append("\n## Magnitude sweep (200 literatures per cell): coverage / rate of certified benefit\n")
        meths = None
        for key, v in sw.items():
            ms = [m for m, x in v.items() if isinstance(x, dict) and "coverage" in x]
            if meths is None:
                meths = ms
                out.append("| Family and multiplier | " + " | ".join(meths) + " |")
                out.append("|---" * (len(meths) + 1) + "|")
            out.append(f"| {key.replace(' | ', ', ')} | " + " | ".join(f"{f(v[m]['coverage'], 3)} / {f(v[m]['benefit'], 2)}" for m in meths) + " |")
    open("tables_simulation.md", "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
